import path from "node:path";

import * as NodeFileSystem from "@effect/platform-node/NodeFileSystem";
import { Effect, FileSystem, Layer } from "effect";
import type { Plugin, UserConfig } from "vite";
import { defaultAllowedOrigins } from "vite";

import { RadicalAdapter } from "../../core/adapter/adapter.ts";
import { bundledOrigins } from "../../core/bundled/bundled-request.ts";
import {
  NativeMetadata,
  nativeMetadataLayer,
} from "../../native/shared/native-metadata.ts";
import { BuildPlanApi } from "../build-plan-api.ts";
import { resolveBuildPlan } from "../build-plan.ts";
import type { BuildPlan } from "../build-plan.ts";
import type { RadicalConfig } from "../config.ts";
import { pluginModulesLayer } from "./plugin-plan.ts";
import type { EnabledPlugin, PluginModules } from "./plugin-plan.ts";

const modulePath = (root: string, module: string) =>
  module.startsWith(".") ? path.resolve(root, module) : module;

export const pluginVirtualSource = (
  root: string,
  plugins: readonly EnabledPlugin[],
  effect = false
) =>
  [
    `import { createPluginClient } from "@akshatowo/radical/${effect ? "effect/" : ""}plugins";`,
    ...plugins.map(
      (entry, index) =>
        `import { ${entry.selector} as manifest${index} } from ${JSON.stringify(modulePath(root, entry.module))};`
    ),
    effect
      ? `export const plugins = {${plugins.map((entry, index) => `${JSON.stringify(entry.manifest.id)}: createPluginClient(manifest${index})`).join(",")}};`
      : `export const createPlugins = (runtime) => ({${plugins.map((entry, index) => `${JSON.stringify(entry.manifest.id)}: createPluginClient(manifest${index}, runtime)`).join(",")}}); export const plugins = createPlugins();`,
  ].join("\n");

const pluginDeclarations = (
  root: string,
  plugins: readonly EnabledPlugin[],
  effect: boolean
) =>
  [
    "// Generated by radical. Run Vite after changing enabled plugins.",
    `declare module "virtual:radical/${effect ? "effect/" : ""}plugins" {`,
    "  export const plugins: {",
    ...plugins.map(
      (entry) =>
        `    readonly ${JSON.stringify(entry.manifest.id)}: import("@akshatowo/radical/${effect ? "effect/" : ""}plugins").PluginClient<typeof import(${JSON.stringify(modulePath(root, entry.module))})[${JSON.stringify(entry.selector)}]>;`
    ),
    "  };",
    ...(effect
      ? []
      : [
          '  export const createPlugins: (runtime?: import("@akshatowo/radical/client").RadicalRuntime) => typeof plugins;',
        ]),
    "}",
    "",
  ].join("\n");

export const pluginTypeSource = (
  root: string,
  plugins: readonly EnabledPlugin[]
) =>
  pluginDeclarations(root, plugins, false) +
  pluginDeclarations(root, plugins, true);

export const nativePlugins = (
  config: RadicalConfig,
  adapterLayer?: Layer.Layer<RadicalAdapter>,
  services?: Layer.Layer<PluginModules | FileSystem.FileSystem>
): Plugin => {
  let source = "";
  let effectSource = "";
  let plan: BuildPlan | undefined;

  const resolvePlan = (root: string) =>
    Effect.suspend(() =>
      plan === undefined
        ? resolveBuildPlan(config).pipe(
            Effect.provide(services ?? pluginModulesLayer(root)),
            Effect.tap((value) =>
              Effect.sync(() => {
                plan = value;
              })
            )
          )
        : Effect.succeed(plan)
    );

  const browserConfig = JSON.stringify({
    appId: config.appId,
    mode: config.mode ?? "remote",
    origin: config.origin,
  });

  return {
    name: "radical:plugins",
    api: new BuildPlanApi(resolvePlan),
    config: (user) =>
      Effect.runPromise(
        resolvePlan(user.root ?? process.cwd()).pipe(
          Effect.map((value) => {
            const result: UserConfig = {
              define: value.defines,
              server: {
                host: user.server?.host ?? "0.0.0.0",
                watch: { ignored: ["**/.radical/**"] },
              },
            };

            if (
              config.mode === "bundled" &&
              user.server?.cors === undefined &&
              result.server
            ) {
              result.server.cors = {
                origin: (origin, callback) => {
                  // False skips Vite's CORS middleware; preview inherits this policy.
                  const policy = bundledOrigins.some(
                    (bundled) => bundled === origin
                  )
                    ? false
                    : defaultAllowedOrigins;

                  // @ts-expect-error Vite's callback type omits the valid null success argument.
                  callback(null, policy);
                },
              };
            }

            return result;
          })
        )
      ),
    configResolved: (resolved) =>
      Effect.runPromise(
        Effect.gen(function* () {
          const { plugins } = yield* resolvePlan(resolved.root);
          source = pluginVirtualSource(resolved.root, plugins);
          effectSource = pluginVirtualSource(resolved.root, plugins, true);
          const fs = yield* FileSystem.FileSystem;
          const metadata = yield* NativeMetadata;

          const outputs = adapterLayer
            ? yield* RadicalAdapter.pipe(
                Effect.flatMap((adapter) => adapter.outputs),
                Effect.provide(adapterLayer)
              )
            : undefined;

          yield* metadata.update(resolved.root, config, undefined, outputs);
          yield* fs.makeDirectory(path.join(resolved.root, ".radical"), {
            recursive: true,
          });
          const file = path.join(resolved.root, ".radical/plugins.d.ts");
          const declarations = `${pluginTypeSource(resolved.root, plugins)}\ndeclare module "virtual:radical/config" { export const config: { readonly appId: string; readonly mode: "remote" | "bundled"; readonly origin?: string }; }\n`;

          // Preserve mtime to avoid restarting Vite's watcher on identical config.
          if (
            (yield* fs
              .readFileString(file)
              .pipe(Effect.orElseSucceed(() => ""))) !== declarations
          ) {
            yield* fs.writeFileString(file, declarations);
          }
        }).pipe(
          Effect.provide(
            Layer.merge(
              services ??
                Layer.merge(
                  pluginModulesLayer(resolved.root),
                  NodeFileSystem.layer
                ),
              nativeMetadataLayer.pipe(
                Layer.provide(services ?? NodeFileSystem.layer)
              )
            )
          )
        )
      ),
    resolveId: (id) =>
      id === "virtual:radical/plugins" ||
      id === "virtual:radical/effect/plugins" ||
      id === "virtual:radical/config"
        ? `\0${id}`
        : undefined,
    load: (id) => {
      if (id === "\0virtual:radical/config") {
        return `export const config = ${browserConfig};`;
      }

      if (id === "\0virtual:radical/plugins") {
        return source;
      }

      if (id === "\0virtual:radical/effect/plugins") {
        return effectSource;
      }

      return null;
    },
  };
};
