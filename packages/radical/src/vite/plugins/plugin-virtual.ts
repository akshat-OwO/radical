import path from "node:path";

import * as NodeFileSystem from "@effect/platform-node/NodeFileSystem";
import { Effect, FileSystem, Layer } from "effect";
import type { Plugin } from "vite";

import {
  NativeMetadata,
  nativeMetadataLayer,
} from "../../native/shared/native-metadata.ts";
import type { RadicalConfig } from "../config.ts";
import { resolvePlugins, pluginModulesLayer } from "./plugin-plan.ts";
import type { EnabledPlugin } from "./plugin-plan.ts";

const modulePath = (root: string, module: string) =>
  module.startsWith(".") ? path.resolve(root, module) : module;
export const pluginVirtualSource = (
  root: string,
  plugins: readonly EnabledPlugin[]
) =>
  [
    'import { createPluginClient } from "radical/plugins";',
    ...plugins.map(
      (entry, index) =>
        `import { ${entry.selector} as manifest${index} } from ${JSON.stringify(modulePath(root, entry.module))};`
    ),
    `export const plugins = {${plugins.map((entry, index) => `${JSON.stringify(entry.manifest.id)}: createPluginClient(manifest${index})`).join(",")}};`,
  ].join("\n");
export const pluginTypeSource = (
  root: string,
  plugins: readonly EnabledPlugin[]
) =>
  [
    "// Generated by radical. Run Vite after changing enabled plugins.",
    'declare module "virtual:radical/plugins" {',
    "  export const plugins: {",
    ...plugins.map(
      (entry) =>
        `    readonly ${JSON.stringify(entry.manifest.id)}: import("radical/plugins").PluginClient<typeof import(${JSON.stringify(modulePath(root, entry.module))})[${JSON.stringify(entry.selector)}]>;`
    ),
    "  };",
    "}",
    "",
  ].join("\n");
export const nativePlugins = (config: RadicalConfig): Plugin => {
  let source = "";
  const browserConfig = JSON.stringify({
    appId: config.appId,
    mode: config.mode ?? "remote",
    origin: config.origin,
  });
  return {
    name: "radical:plugins",
    configResolved: (resolved) =>
      Effect.runPromise(
        Effect.gen(function* () {
          const plugins = yield* resolvePlugins(config);
          source = pluginVirtualSource(resolved.root, plugins);
          const fs = yield* FileSystem.FileSystem;
          const metadata = yield* NativeMetadata;
          yield* metadata.update(resolved.root, config);
          yield* fs.makeDirectory(path.join(resolved.root, ".radical"), {
            recursive: true,
          });
          const file = path.join(resolved.root, ".radical/plugins.d.ts");
          const declarations = `${pluginTypeSource(resolved.root, plugins)}\ndeclare module "virtual:radical/config" { export const config: { readonly appId: string; readonly mode: "remote" | "bundled"; readonly origin?: string }; }\n`;
          // Preserve mtime to avoid restarting Vite's watcher on identical config.
          if (
            (yield* fs
              .readFileString(file)
              .pipe(Effect.orElseSucceed(() => ""))) !== declarations
          ) {
            yield* fs.writeFileString(file, declarations);
          }
        }).pipe(
          Effect.provide(
            Layer.mergeAll(
              pluginModulesLayer(resolved.root),
              NodeFileSystem.layer,
              nativeMetadataLayer.pipe(Layer.provide(NodeFileSystem.layer))
            )
          )
        )
      ),
    resolveId: (id) =>
      id === "virtual:radical/plugins" || id === "virtual:radical/config"
        ? `\0${id}`
        : undefined,
    load: (id) => {
      if (id === "\0virtual:radical/config") {
        return `export const config = ${browserConfig};`;
      }
      return id === "\0virtual:radical/plugins" ? source : undefined;
    },
  };
};
